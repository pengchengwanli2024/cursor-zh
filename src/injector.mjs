/**
 * 运行时注入：把翻译脚本挂进渲染进程。
 *
 * 两个目标：
 *   workbench  主窗口（编辑器 + 设置页），入口是 workbench.html
 *   molten     智能体窗口（Cursor 3.31 起的独立渲染进程），入口是 molten/dist/renderer/index.html
 *
 * 两处 CSP 都允许 script-src 'self'，同目录脚本可以直接加载，不需要放宽安全策略。
 */
import fs from 'node:fs';
import path from 'node:path';

export const WORKBENCH_HTML_REL = 'vs/code/electron-sandbox/workbench/workbench.html';
export const RUNTIME_REL = 'vs/code/electron-sandbox/workbench/cursor-zh.js';

export const MOLTEN_HTML_REL = 'molten/dist/renderer/index.html';
export const MOLTEN_RUNTIME_REL = 'molten/dist/renderer/cursor-zh.js';

const WORKBENCH_MARKER = '<script src="./workbench.js"';
const WORKBENCH_TAG = '<script src="./cursor-zh.js"></script>';
const MOLTEN_MARKER = '<script type="module" crossorigin src="./assets/document-';
const MOLTEN_TAG = '<script src="./cursor-zh.js"></script>';

export function workbenchHtml(appRoot) {
  return path.join(appRoot, 'out', WORKBENCH_HTML_REL);
}

export function runtimeFile(appRoot) {
  return path.join(appRoot, 'out', RUNTIME_REL);
}

export function moltenHtml(appRoot) {
  return path.join(appRoot, 'molten', 'dist', 'renderer', 'index.html');
}

export function moltenRuntimeFile(appRoot) {
  return path.join(appRoot, 'molten', 'dist', 'renderer', 'cursor-zh.js');
}

/** 生成运行时脚本内容（词典内联，避免额外请求与 CSP 限制）。 */
export function buildRuntimeSource(runtimeTemplate, dictJson) {
  const payload =
    'window.__CURSOR_ZH_DICT=' + JSON.stringify(dictJson.dict) + ';\n' +
    'window.__CURSOR_ZH_PATTERNS=' + JSON.stringify(dictJson.patterns || []) + ';\n';
  const patched = runtimeTemplate.replace(
    'var PATTERNS = window.__CURSOR_ZH_PATTERNS || [];',
    'var PATTERNS = (window.__CURSOR_ZH_PATTERNS || []).map(function (p) { try { return { re: new RegExp(p.s, p.f || ""), zh: p.z }; } catch (e) { return null; } }).filter(Boolean);',
  );
  return '/* generated by cursor-zh; do not edit. */\n' + payload + patched;
}

/** workbench.html 是否已注入。 */
export function isInjected(appRoot) {
  try {
    return fs.readFileSync(workbenchHtml(appRoot), 'utf8').includes('cursor-zh.js');
  } catch { return false; }
}

/** 智能体窗口是否已注入。 */
export function isMoltenInjected(appRoot) {
  try {
    return fs.readFileSync(moltenHtml(appRoot), 'utf8').includes('cursor-zh.js');
  } catch { return false; }
}

function atomicWrite(file, content) {
  const tmp = file + '.' + process.pid + '.cursor-zh.tmp';
  fs.writeFileSync(tmp, content, 'utf8');
  fs.renameSync(tmp, file);
}

/** 往一个 HTML 的指定锚点前插入脚本标签。 */
function injectHtml(htmlFile, marker, tag) {
  const src = fs.readFileSync(htmlFile, 'utf8');
  if (src.includes('cursor-zh.js')) return { injected: true, updated: false };
  if (!src.includes(marker)) return { injected: false, updated: false, reason: '页面结构不符预期' };
  atomicWrite(htmlFile, src.replace(marker, tag + '\n    ' + marker));
  return { injected: true, updated: false };
}

function uninjectHtml(htmlFile, tag) {
  if (!fs.existsSync(htmlFile)) return false;
  const src = fs.readFileSync(htmlFile, 'utf8');
  if (!src.includes('cursor-zh.js')) return false;
  atomicWrite(htmlFile, src.replace(new RegExp('\\s*' + tag.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')), ''));
  return true;
}

/** 注入主窗口运行时。 */
export function inject(appRoot, runtimeSource) {
  const html = workbenchHtml(appRoot);
  if (!fs.existsSync(html)) return { injected: false, updated: false, reason: '找不到 workbench.html' };
  const had = isInjected(appRoot);
  fs.writeFileSync(runtimeFile(appRoot), runtimeSource, 'utf8');
  const r = injectHtml(html, WORKBENCH_MARKER, WORKBENCH_TAG);
  return { ...r, updated: had };
}

/** 注入智能体窗口运行时。 */
export function injectMolten(appRoot, runtimeSource) {
  const html = moltenHtml(appRoot);
  if (!fs.existsSync(html)) return { injected: false, updated: false, reason: '未检测到智能体窗口（旧版 Cursor）' };
  const had = isMoltenInjected(appRoot);
  fs.writeFileSync(moltenRuntimeFile(appRoot), runtimeSource, 'utf8');
  const r = injectHtml(html, MOLTEN_MARKER, MOLTEN_TAG);
  return { ...r, updated: had };
}

/** 移除主窗口注入。 */
export function uninject(appRoot) {
  uninjectHtml(workbenchHtml(appRoot), WORKBENCH_TAG);
  try { fs.rmSync(runtimeFile(appRoot), { force: true }); } catch { /* 已不存在 */ }
}

/** 移除智能体窗口注入。 */
export function uninjectMolten(appRoot) {
  uninjectHtml(moltenHtml(appRoot), MOLTEN_TAG);
  try { fs.rmSync(moltenRuntimeFile(appRoot), { force: true }); } catch { /* 已不存在 */ }
}
